"""series (F07 design 3.1, 8.7 D66, 14.1; part 2 note, series; F06 design 5.4).

The engine plans the series lock from the config at HEAD and runs nothing:
the commands that compile and install the lock, each member's tests, and the
members whose lock is now stale. The manifests and the compile options are
troy-init's (``troyinit.env.manifests`` and ``troyinit.packs.PACKS``).

Planted bug of design 14.2 caught here: "a member's stale lock missed":
``SeriesTests.test_stale_members_come_from_file_contents`` and
``test_missing_member_lock_is_stale``.
"""

import sys
import unittest

from flow_helpers import (
    CONFIG, ENVIRONMENT, PLUGIN_ROOT, SCRATCH, Fakes, FlowCase, Project, base_files,
    base_step, config_text, crlf, new_dir, parallel, run_engine, same_path, split_command,
    write_file,
)

_INIT = str(PLUGIN_ROOT / "troy-mode/init")
if _INIT not in sys.path:
    sys.path.insert(0, _INIT)

from troyinit.env import manifests  # noqa: E402  (after the path setup)
from troyinit.packs import PACKS  # noqa: E402

PREFIX = "/scratch/troy-env"
PY_LOCK = "requirements-dev.lock"
CPP_LOCK = "requirements-tools.lock"
LOCK_TEXT = "# This file was autogenerated by uv.\nclick==8.1.7\nruff==0.6.9\n"
OTHER_LOCK = "# This file was autogenerated by uv.\nclick==8.1.8\nruff==0.6.9\n"
PY_TESTS = [["python", "-m", "pytest", "-q"]]
CPP_TESTS = [["cmake", "--preset", "coverage"], ["cmake", "--build", "--preset", "coverage"],
             ["ctest", "--preset", "coverage"]]


def lang_config(lang: str = "python", series=None) -> str:
    """A config with a ``[lang]`` table and a chosen ``series``.

    Args:
        lang: ``python`` or ``cpp``.
        series: The member folders, or None to leave ``series`` out.

    Returns:
        The TOML text.
    """
    roots = 'source_roots = ["src"]' if lang == "python" else 'include_dirs = ["include", "src"]'
    text = (config_text(lang=None) + f'\n[lang]\nname = "{lang}"\n{roots}\n'
            f'environment = "{ENVIRONMENT}"\n')
    if series is not None:
        text += "series = [" + ", ".join(f'"{member}"' for member in series) + "]\n"
    return text


def series_project(config: str, lock: str = PY_LOCK, lock_text=LOCK_TEXT,
                   members=None, install_lang="python") -> Project:
    """A clone whose HEAD has the config and the lock, with sibling member folders.

    Args:
        config: The config text.
        lock: The lock's path.
        lock_text: The lock's content, or None for no lock.
        members: A folder name next to the clone mapped to its lock's content
            (bytes or text), or None for a folder without a lock.
        install_lang: The pack in the install record, or None.

    Returns:
        The clone.
    """
    extra = {CONFIG: config}
    if lock_text is not None:
        extra[lock] = lock_text
    project = Project([base_step(base_files(lang=install_lang, extra=extra))])
    for folder, content in (members or {}).items():
        (project.tmp / folder).mkdir()
        write_file(project.tmp / folder, "pyproject.toml", f'[project]\nname = "{folder}"\n')
        if content is not None:
            write_file(project.tmp / folder, lock, content)
    return project


def command_words(command: str) -> tuple:
    """Splits ``[UV_LINK_MODE=copy] <mamba> run <target> <rest>``.

    Args:
        command: The command line.

    Returns:
        ``(prefix words before the program, program, target words, rest words)``.

    Raises:
        AssertionError: The command has no ``<mamba> run -n|-p <value>``.
    """
    words = split_command(command)
    start = 1 if words and words[0].startswith("UV_LINK_MODE=") else 0
    if len(words) < start + 4 or words[start + 1] != "run" or words[start + 2] not in ("-n",
                                                                                        "-p"):
        raise AssertionError(f"not a mamba run command: {command!r}")
    return words[:start], words[start], words[start + 2:start + 4], words[start + 4:]


def snapshot(project: Project, folders) -> tuple:
    """The clone's status and every file of the member folders, to compare after a run."""
    files = {}
    for folder in folders:
        root = project.tmp / folder
        if root.is_dir():
            for path in sorted(root.rglob("*")):
                if path.is_file():
                    files[path.relative_to(project.tmp).as_posix()] = path.read_bytes()
    return project.status_lines(), project.head(), files


class SeriesTests(FlowCase):
    """The Python pack with three members: one current, one stale (design 8.7, D66)."""

    SERIES = [".", "../troy-voice", "../troy-cli"]
    FOLDERS = ("troy-voice", "troy-cli")

    @classmethod
    def setUpClass(cls):
        """One clone; series runs once with a named environment and once with a prefix."""
        cls.project = series_project(lang_config(series=cls.SERIES), members={
            "troy-voice": crlf(LOCK_TEXT), "troy-cli": OTHER_LOCK})
        cls.fakes = Fakes(fail=True)
        before = snapshot(cls.project, cls.FOLDERS)
        cls.named = cls.project.run("series", fakes=cls.fakes)
        cls.prefixed = cls.project.run("series", fakes=cls.fakes,
                                       env_extra={"TROY_MODE_ENV_PREFIX": PREFIX})
        cls.unchanged = snapshot(cls.project, cls.FOLDERS) == before

    def report(self, prefixed: bool = False) -> dict:
        """The report of one run, which must exit 0."""
        return self.report_of(self.prefixed if prefixed else self.named, 0, "series")

    def test_pack_and_lock(self):
        """The Python pack's lock file."""
        report = self.report()
        self.assertEqual((report["lang"], report["lock"]), ("python", PY_LOCK))

    def test_compile_then_install_with_copied_files(self):
        """Two commands, compile then install, each with ``UV_LINK_MODE=copy`` and mamba run."""
        commands = self.report()["commands"]
        self.assertEqual(len(commands), 2, commands)
        compile_words, install_words = (command_words(c) for c in commands)
        for prefix, program, target, _ in (compile_words, install_words):
            self.assertEqual(prefix, ["UV_LINK_MODE=copy"])
            self.assertTrue(same_path(program, self.fakes.mamba), program)
            self.assertEqual(target, ["-n", ENVIRONMENT])
        self.assertEqual(compile_words[3][:3], ["uv", "pip", "compile"])
        self.assertEqual(install_words[3], ["uv", "pip", "install", "-r", PY_LOCK])

    def test_lock_is_compiled_from_every_manifest_in_series_order(self):
        """``uv pip compile`` gets troy-init's manifests in series order, the pack's options,
        and ``-o <lock>``."""
        rest = command_words(self.report()["commands"][0])[3]
        expected = (["uv", "pip", "compile", *manifests(PACKS["python"], self.SERIES),
                     *PACKS["python"].compile_args, "-o", PY_LOCK])
        self.assertEqual(rest, expected)
        self.assertEqual(rest[3:6], ["pyproject.toml", "../troy-voice/pyproject.toml",
                                     "../troy-cli/pyproject.toml"])

    def test_members_in_series_order(self):
        """One entry per member: this project without tests, the others with pytest in their
        own folder."""
        members = self.report()["members"]
        self.assertEqual([(m["path"], m["this"], m["exists"], m["stale"]) for m in members],
                         [(".", True, True, False), ("../troy-voice", False, True, False),
                          ("../troy-cli", False, True, True)])
        self.assertIsNone(members[0]["tests"])
        for member in members[1:]:
            with self.subTest(member=member["path"]):
                self.assertEqual(member["tests"]["cwd"], member["path"])
                words = [command_words(c) for c in member["tests"]["commands"]]
                self.assertEqual([w[3] for w in words], PY_TESTS)
                self.assertEqual([w[2] for w in words], [["-n", ENVIRONMENT]])
                self.assertEqual([w[0] for w in words], [[]])

    def test_stale_members_come_from_file_contents(self):
        """Planted bug "a member's stale lock missed": a CRLF copy is current, a changed
        one is stale."""
        self.assertEqual(self.report()["stale"], ["../troy-cli"])

    def test_env_prefix_sets_every_target(self):
        """With ``TROY_MODE_ENV_PREFIX``: ``-p <prefix>`` in every command, ``-n`` in none."""
        report = self.report(prefixed=True)
        commands = list(report["commands"])
        for member in report["members"]:
            if member["tests"]:
                commands += member["tests"]["commands"]
        self.assertEqual(len(commands), 4, commands)
        for command in commands:
            with self.subTest(command=command):
                self.assertEqual(command_words(command)[2], ["-p", PREFIX])

    def test_runs_nothing_and_writes_nothing(self):
        """The fake mamba and gh are never called; the clone and the members are unchanged."""
        self.report()
        self.assertEqual(self.fakes.mamba_calls(), [])
        self.assertEqual(self.fakes.gh_calls(), [])
        self.assertTrue(self.unchanged, "series changed the clone or a member folder")


class SeriesCaseTests(FlowCase):
    """C/C++, the default series, the config at HEAD, the working tree's lock, and refusals."""

    @classmethod
    def setUpClass(cls):
        """Builds one clone per case and runs series on each, side by side."""
        def head_config():
            """series at HEAD names one member; the working tree adds a missing one."""
            project = series_project(lang_config(series=[".", "../troy-voice"]),
                                     members={"troy-voice": LOCK_TEXT})
            project.write(CONFIG, lang_config(series=[".", "../troy-voice", "../troy-gone"]))
            return project

        def tree_lock():
            """HEAD's lock is old; the working tree holds a newly compiled one in CRLF."""
            project = series_project(lang_config(series=[".", "../troy-voice", "../troy-cli"]),
                                     lock_text=OTHER_LOCK,
                                     members={"troy-voice": LOCK_TEXT, "troy-cli": OTHER_LOCK})
            project.write(PY_LOCK, crlf(LOCK_TEXT))
            return project

        builders = {
            "cpp": lambda: series_project(lang_config("cpp", [".", "../troy-tools"]), CPP_LOCK,
                                          members={"troy-tools": None}, install_lang="cpp"),
            "default series": lambda: series_project(lang_config(series=None)),
            "head config": head_config,
            "tree lock": tree_lock,
            "missing member": lambda: series_project(lang_config(series=[".", "../troy-gone"])),
            "no language": lambda: series_project(config_text(lang=None), install_lang=None),
            "invalid config": lambda: series_project(config_text(extra="[bogus]\nx = 1\n")),
        }
        names = list(builders)
        cls.fakes = Fakes(fail=True)
        outs = parallel(lambda name: builders[name]().run("series", fakes=cls.fakes), names)
        cls.outs = dict(zip(names, outs))

    def test_cpp_pack(self):
        """C/C++: its lock, its manifest per member, its options, and cmake and ctest."""
        report = self.report_of(self.outs["cpp"], 0, "series")
        self.assertEqual((report["lang"], report["lock"]), ("cpp", CPP_LOCK))
        series = [".", "../troy-tools"]
        compile_rest = command_words(report["commands"][0])[3]
        self.assertEqual(compile_rest, ["uv", "pip", "compile",
                                        *manifests(PACKS["cpp"], series),
                                        *PACKS["cpp"].compile_args, "-o", CPP_LOCK])
        self.assertEqual(compile_rest[3:5], ["requirements-tools.in",
                                             "../troy-tools/requirements-tools.in"])
        self.assertEqual(command_words(report["commands"][1])[3],
                         ["uv", "pip", "install", "-r", CPP_LOCK])
        tools = report["members"][1]
        self.assertEqual((tools["path"], tools["this"], tools["exists"]),
                         ("../troy-tools", False, True))
        self.assertEqual(tools["tests"]["cwd"], "../troy-tools")
        self.assertEqual([command_words(c)[3] for c in tools["tests"]["commands"]], CPP_TESTS)

    def test_missing_member_lock_is_stale(self):
        """Planted bug "a member's stale lock missed": a member without the lock is stale."""
        report = self.report_of(self.outs["cpp"], 0, "series")
        self.assertIs(report["members"][1]["stale"], True)
        self.assertEqual(report["stale"], ["../troy-tools"])

    def test_default_series_is_this_project(self):
        """No ``series`` key: the one member ``.``, one manifest, nothing stale."""
        report = self.report_of(self.outs["default series"], 0, "series")
        self.assertEqual(report["members"], [{"path": ".", "this": True, "exists": True,
                                              "stale": False, "tests": None}])
        self.assertEqual(command_words(report["commands"][0])[3],
                         ["uv", "pip", "compile", "pyproject.toml",
                          *PACKS["python"].compile_args, "-o", PY_LOCK])
        self.assertEqual(report["stale"], [])

    def test_series_comes_from_the_config_at_head(self):
        """A member added only in the working tree's config, and missing, changes nothing."""
        report = self.report_of(self.outs["head config"], 0, "series")
        self.assertEqual([m["path"] for m in report["members"]], [".", "../troy-voice"])
        self.assertEqual(report["stale"], [])

    def test_lock_is_read_from_the_working_tree(self):
        """The new lock in the working tree (CRLF) equals one member's (LF); the other is stale."""
        report = self.report_of(self.outs["tree lock"], 0, "series")
        self.assertEqual([(m["path"], m["stale"]) for m in report["members"]],
                         [(".", False), ("../troy-voice", False), ("../troy-cli", True)])
        self.assertEqual(report["stale"], ["../troy-cli"])

    def test_missing_member_folder_is_a_problem(self):
        """A member folder that does not exist: exit 1, and the problem names it."""
        report = self.report_of(self.outs["missing member"], 1, "series")
        self.assertIn("troy-gone", str(report["problems"]))

    def test_no_language_is_a_problem(self):
        """No ``[lang] name`` at HEAD: exit 1 with a problem."""
        report = self.report_of(self.outs["no language"], 1, "series")
        self.assertNotEqual(report["problems"], [])

    def test_invalid_config_exits_two(self):
        """A config troy-check rejects: the engine cannot run."""
        self.assert_exit(self.outs["invalid config"], 2)

    def test_mamba_is_never_run(self):
        """No case runs the fake mamba."""
        self.assertEqual(self.fakes.mamba_calls(), [])

    def test_outside_a_repository_exits_two(self):
        """``--repo`` naming a plain folder: exit 2."""
        out = run_engine(["series", "--repo", new_dir("plain"), "--json"], SCRATCH,
                         Fakes(fail=True))
        self.assert_exit(out, 2)


if __name__ == "__main__":
    unittest.main()
